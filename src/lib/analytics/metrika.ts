/** Номер счётчика Яндекс.Метрики. Задаётся окружением
 *  (NEXT_PUBLIC_YM_COUNTER_ID). Пусто — Метрика не подключается вовсе:
 *  ни счётчика, ни целей, ни кук. Так на локали и до выдачи номера
 *  аналитики просто нет. */
export const YM_COUNTER_ID = process.env.NEXT_PUBLIC_YM_COUNTER_ID ?? '';

type YmFn = (id: string | number, method: string, ...args: unknown[]) => void;

function ym(): YmFn | undefined {
  if (typeof window === 'undefined') return undefined;
  return (window as unknown as { ym?: YmFn }).ym;
}

/** Просмотр страницы при переходе внутри сайта. Счётчик инициализируется
 *  с defer:true, поэтому первый и последующие показы отправляем сами. */
export function ymHit(url: string): void {
  if (!YM_COUNTER_ID) return;
  ym()?.(YM_COUNTER_ID, 'hit', url);
}

/** Достижение цели. No-op, пока счётчик не задан или скрипт ещё не
 *  загрузился, — вызывающим об этом думать не нужно.
 *
 *  `params` уезжают в параметры визита: по ним в отчёте можно развернуть
 *  цель по объектам, разделам меню и мессенджерам, не заводя под каждый
 *  случай отдельную цель. */
export function reachGoal(
  goal: string,
  params?: Record<string, unknown>,
): void {
  if (!YM_COUNTER_ID) return;
  ym()?.(YM_COUNTER_ID, 'reachGoal', goal, params);
}

