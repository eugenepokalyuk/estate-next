import { ApiError } from '@/services/Api';

/** Превращает ошибку запроса в текст, который не стыдно показать посетителю.
 *
 *  Живёт в сторе, а не в компонентах: тексты одни на все формы и списки,
 *  и раскладывать их по местам вызова значило бы поддерживать несколько
 *  версий одной и той же фразы.
 */
export function toErrorMessage(error: unknown): string {
  if (!(error instanceof ApiError)) {
    return 'Что-то пошло не так. Попробуйте позже.';
  }

  // Валидация не прошла — показываем ровно то, что сказал сервер.
  const fieldError = error.firstFieldError;
  if (error.status === 400 && fieldError) return fieldError;

  switch (error.status) {
    case 0:
      return 'Не получилось связаться с сервером — проверьте связь и попробуйте ещё раз.';
    case 400:
      return 'Проверьте заполнение формы.';
    case 404:
      return 'Не найдено.';
    // Слишком частая отправка. Отдельный текст, иначе человек будет жать
    // кнопку и получать одну и ту же «ошибку сервера».
    case 429:
      return 'Слишком много запросов подряд. Попробуйте через несколько минут.';
    default:
      return 'Сервер не отвечает. Попробуйте позже или позвоните нам.';
  }
}
