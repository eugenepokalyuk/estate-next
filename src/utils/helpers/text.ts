/** Разбивает текст из админки на абзацы.
 *
 *  В админке обычное текстовое поле без разметки: менеджер отделяет абзацы
 *  пустой строкой, как в письме. Одиночные переносы внутри абзаца — это
 *  чаще всего перенос по ширине окна, а не намеренный разрыв, поэтому
 *  склеиваем их пробелом.
 */
export function toParagraphs(text: string): string[] {
  return text
    .split(/\n\s*\n/)
    .map((paragraph) => keepOrdinalsWhole(paragraph.trim().replace(/\s*\n\s*/g, ' ')))
    .filter(Boolean);
}

/** Запрещает перенос строки внутри порядкового числительного.
 *
 *  Дефис для браузера — хорошее место для переноса, поэтому «2-й Моховой»
 *  на крупном заголовке разъезжается на «Участок на 2-» и «й Моховой»
 *  следующей строкой. Читается это как опечатка, и адреса вида «2-я
 *  Моховая» в Новосибирске сплошь такие.
 *
 *  Заменяем дефис на неразрывный (U+2011): выглядит он так же, но перенос
 *  по нему запрещён. Правим на показе, а не в админке: в базе должен
 *  лежать обычный дефис — по нему объект ищут и в поиске, и внутри сайта,
 *  а неразрывный поисковому запросу не совпадёт.
 *
 *  Только между цифрой и буквой. В «Мамина-Сибиряка» перенос по дефису
 *  как раз уместен, а «10-15 соток» и телефон «123-45-67» правило не
 *  трогает — там с обеих сторон цифры.
 */
export function keepOrdinalsWhole(text: string): string {
  // Escape-последовательностью, а не самим символом: глазами в коде
  // неразрывный дефис от обычного не отличить.
  return text.replace(/(\d)-(?=[а-яёa-z])/gi, '$1\u2011');
}
